function updateCannonOrientation () {

  if (cannonBody) {
    const radians = (cannonAngle * Math.PI) / 180;
    cannonBody.quaternion.setFromAxisAngle(new CANNON.Vec3(0, 1, 0), radians);
    //sets angle with respect to the y-axis
  }
}

function animate () {
    requestAnimationFrame(animate);


    world.step(1 / 60);
  //animation update time

  for (let i = 0; i < cannonBalls.length; i++) {
    ball = cannonBalls[i];
    if (i < ballMeshes.length) //checks if the ball mesh and ball have been created
    {
      ballMeshes[i].position.copy(ball.position);
      ballMeshes[i].quaternion.copy(ball.quaternion);
    }
  }
  // lines 277-285 were generated by ai
  //makes the ball mesh have the same position and rotation as the ball


  renderer.render(scene, camera);
}


